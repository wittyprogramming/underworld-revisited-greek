def parse_block4(path):
    rows = {}
    lines = path.read_text(encoding="utf-8").splitlines(True)
    i = 0
    while i < len(lines):
        if lines[i].startswith("#@"):
            chk = lines[i].rstrip("\n")
            nxt = lines[i + 1]
            parts = nxt.rstrip("\n").split("\t", 2)
            if len(parts) == 3 and parts[0] == "4":
                rows[chk] = parts[2]
        i += 1
    return rows


uw1 = parse_block4(UW1)
text = UW2.read_text(encoding="utf-8")
lines = text.splitlines(True)
out = []
i = 0
copied = 0
newed = 0
while i < len(lines):
    line = lines[i]
    if line.startswith("#@"):
        chk = line.rstrip("\n")
        nxt = lines[i + 1]
        parts = nxt.rstrip("\n").split("\t", 2)
        if len(parts) == 3 and parts[0] == "4":
            idx = int(parts[1])
            if idx in NEW:
                greek = NEW[idx]
                newed += 1
            elif chk in uw1:
                greek = uw1[chk]
                copied += 1
            else:
                raise SystemExit(f"missing translation for {idx} {parts[2]!r}")
            out.append(line)
            nl = "\n" if nxt.endswith("\n") else ""
            out.append(f"4\t{idx}\t{greek}{nl}")
            i += 2
            continue
    out.append(line)
    i += 1

UW2.write_text("".join(out), encoding="utf-8")
print(f"copied {copied} new {newed}")
