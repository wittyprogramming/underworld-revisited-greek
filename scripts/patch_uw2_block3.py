def parse_block(path: Path, block: int):
    bychk = {}
    byen = {}
    chk = None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("#@ "):
            chk = line[3:].strip()
            continue
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t", 2)
        if len(parts) < 3:
            continue
        b, i, t = int(parts[0]), int(parts[1]), parts[2]
        if b == block and chk:
            bychk[chk] = t
            byen[t] = t  # placeholder
        chk = None
    return bychk


