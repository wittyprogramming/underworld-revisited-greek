def nm(g, nom, acc=None, gen=None, art=""):
    s = f"{g}{art}:{nom}"
    cases = []
    if acc:
        cases.append(f"acc={acc}")
    if gen:
        cases.append(f"gen={gen}")
    if cases:
        s += "|" + "|".join(cases)
    return s


def m(nom, acc=None, gen=None, art=""):
    return nm("m", nom, acc=acc, gen=gen, art=art)


def f(nom, acc=None, gen=None, art=""):
    return nm("f", nom, acc=acc, gen=gen, art=art)


def n(nom, gen=None, art=""):
    return nm("n", nom, gen=gen, art=art)


