while i < len(lines):
    line = lines[i]
    out.append(line)
    if line.startswith("#") or not line.strip():
        i += 1
        continue
    parts = line.split("\t", 2)
    if len(parts) >= 3:
        try:
            b, idx = int(parts[0]), int(parts[1])
        except ValueError:
            i += 1
            continue
        key = (b, idx)
        if key in T:
            nl = "\n" if line.endswith("\n") and not line.endswith("\r\n") else ("\r\n" if line.endswith("\r\n") else "")
            # keep original line ending; content without ending
            new = f"{b}\t{idx}\t{T[key]}{nl}"
            out[-1] = new
            n += 1
            del T[key]
    i += 1

