def main():
    lines = UW2.read_text(encoding="utf-8").splitlines(keepends=True)
    out = []
    chk = None
    n_copy = n_new = n_keep = 0
    for line in lines:
        raw = line[:-1] if line.endswith("\n") else line
        if raw.endswith("\r"):
            raw = raw[:-1]
        if raw.startswith("#@ "):
            chk = raw[3:].strip()
            out.append(line)
            continue
        if raw and not raw.startswith("#"):
            parts = raw.split("\t", 2)
            if len(parts) >= 3:
                b, i = int(parts[0]), int(parts[1])
                if b == 1:
                    if i in NEW:
                        text = NEW[i]
                        n_new += 1
                    elif chk in uw1:
                        text = uw1[chk]
                        n_copy += 1
                    else:
                        text = parts[2]
                        n_keep += 1
                    nl = "\n" if line.endswith("\n") else ""
                    out.append(f"{b}\t{i}\t{text}{nl}")
                    chk = None
                    continue
        out.append(line)
        if not raw.startswith("#@"):
            chk = None
    UW2.write_text("".join(out), encoding="utf-8")
    print("copy", n_copy, "new", n_new, "keep", n_keep)


if __name__ == "__main__":
    main()
